//! SupplySystem — resupply units from global economy pools.
//!
//! Each tick, units within supply range of friendly cities receive:
//!
//! 1. **Manpower (men)**: deducted from global player manpower pool,
//!    added to unit.men (capped at max_men). Rate limited by `recruitment_rate`.
//! 2. **Equipment**: deducted from global player funds at `cost_per_item`.
//!
//! Supply range uses per-city `supply_range` (grows with city level).
//! Multi-city: closest city at full rate, secondary at decayed rate.

use std::collections::HashMap;

use crate::game::components::*;
use crate::game::game::TickContext;
use crate::game::world_ext::WorldExt;
use hecs::World;

/// Snapshot of a city for planning resupply.
#[derive(Clone)]
struct CitySnapshot {
    position: (f32, f32),
    supply_range_sq: f32,
}

/// Planned resupply for a single unit.
type ResupplyPlan = Vec<(hecs::Entity, String, f32, Vec<(String, u32)>)>;

pub fn run(
    world: &mut World,
    world_entity: hecs::Entity,
    ctx: &TickContext,
    recruitment_rate: f32,
) {
    let decay = {
        let wb = match world.world_data(world_entity) {
            Some(wb) => wb,
            None => return,
        };
        wb.city_upgrades.settings.secondary_city_decay
    };

    // Phase 1: snapshot city data + snapshot entity data
    let all_cities: Vec<CitySnapshot> = {
        let wb = match world.world_data(world_entity) {
            Some(wb) => wb,
            None => return,
        };
        wb.cities
            .cities
            .iter()
            .map(|c| CitySnapshot {
                position: c.position,
                supply_range_sq: c.supply_range * c.supply_range,
            })
            .collect()
    };

    // Collect entities needing resupply with their current stats
    let mut resupply_needed: ResupplyPlan = Vec::new();

    // Snapshot each player's available manpower pool. The pool is a bounded global
    // resource (regenerated by the economy system), so planned resupply must be
    // gated on it — otherwise an exhausted pool would still grant free manpower.
    let mut remaining_mp: HashMap<String, u32> = {
        let wb = match world.world_data(world_entity) {
            Some(wb) => wb,
            None => return,
        };
        wb.funds.manpower.clone()
    };

    for (player_id, entities) in &ctx.units_by_player {
        let player_city_indices: Vec<usize> = all_cities
            .iter()
            .enumerate()
            .filter(|(i, _)| {
                let city = &ctx.cities.get(*i);
                city.map(|c| c.owner.as_deref() == Some(player_id.as_str()))
                    .unwrap_or(false)
            })
            .map(|(i, _)| i)
            .collect();

        if player_city_indices.is_empty() {
            continue;
        }

        for (entity, pos) in entities {
            // Find cities in range
            let mut cities_count = 0usize;
            for &ci in &player_city_indices {
                let city = &all_cities[ci];
                let dx = pos.0 - city.position.0;
                let dy = pos.1 - city.position.1;
                let dist_sq = dx * dx + dy * dy;
                if dist_sq < city.supply_range_sq {
                    cities_count += 1;
                }
            }

            if cities_count == 0 {
                continue;
            }

            // Compute total rate: closest at full rate, others decayed
            let total_rate: f32 = if cities_count == 1 {
                recruitment_rate
            } else {
                recruitment_rate + (cities_count as f32 - 1.0) * recruitment_rate * decay
            };

            // Check if unit needs resupply
            if let Ok(stats) = world.get::<&UnitStats>(*entity) {
                if stats.men >= stats.max_men {
                    continue;
                }
                let deficit = stats.max_men - stats.men;
                let gain = total_rate.min(deficit);
                if gain > 0.0 {
                    // Manpower is a bounded global pool: only plan resupply if this
                    // player still has enough manpower to cover the gain. Units are
                    // served first-come-first-served, and remaining_mp is decremented
                    // so later units never exceed the pool. (Phase 2 then deducts the
                    // same amounts, so the pool can never go negative.)
                    let mp_available = remaining_mp.get(player_id).copied().unwrap_or(0) as f32;
                    if mp_available < gain {
                        continue;
                    }
                    if let Some(mp) = remaining_mp.get_mut(player_id) {
                        *mp -= gain as u32;
                    }
                    resupply_needed.push((*entity, player_id.clone(), gain, Vec::new()));
                }
            }
        }
    }

    // Phase 2: deduct from global pools
    let mp_deductions: HashMap<String, u32> = resupply_needed
        .iter()
        .map(|(_, pid, gain, _)| (pid.clone(), *gain as u32))
        .fold(HashMap::new(), |mut acc, (pid, amt)| {
            *acc.entry(pid).or_insert(0) += amt;
            acc
        });

    {
        let wb = match world.world_data_mut(world_entity) {
            Some(wb) => wb,
            None => return,
        };
        for (pid, amount) in mp_deductions {
            if let Some(mp) = wb.funds.manpower.get_mut(&pid) {
                *mp = mp.saturating_sub(amount);
            }
        }
    }

    // Phase 3: apply to ECS
    for (entity, _pid, gain, _eq_adds) in resupply_needed {
        if let Ok((stats,)) = world.query_one_mut::<(&mut UnitStats,)>(entity) {
            stats.men = (stats.men + gain).min(stats.max_men);
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::config::CityUpgradeSettings;
    use crate::game::economy::City;
    use crate::game::unit::Terrain;

    fn make_world(mp_pool: u32) -> (World, hecs::Entity) {
        let mut world = World::new();
        let mut wb = WorldBundle::new(
            vec![vec![Terrain::Plains; 10]; 10],
            10,
            10,
            CityUpgradeSettings::default(),
            HashMap::new(),
        );
        wb.cities.cities = vec![City {
            id: "c1".to_string(),
            position: (5.0, 5.0),
            owner: Some("P1".to_string()),
            level: 1,
            supply_range: 5.0,
        }];
        wb.funds.manpower.insert("P1".to_string(), mp_pool);
        let world_entity = world.spawn((wb,));
        (world, world_entity)
    }

    fn spawn_unit(world: &mut World, men: f32) -> hecs::Entity {
        world.spawn((
            UnitPosition { x: 5.0, y: 5.0 },
            UnitOwner {
                player_id: "P1".to_string(),
            },
            UnitStats {
                men,
                max_men: 1000.0,
                organisation: 100.0,
                max_organisation: 100.0,
                reinforcement_rate: 5.0,
            },
        ))
    }

    /// An exhausted manpower pool must NOT grant free resupply.
    #[test]
    fn supply_empty_pool_grants_no_manpower() {
        let (mut world, world_entity) = make_world(0); // empty pool
        let unit = spawn_unit(&mut world, 900.0);
        let ctx = TickContext::build(&world, world_entity).unwrap();

        run(&mut world, world_entity, &ctx, 10.0);

        let after = world.get::<&UnitStats>(unit).unwrap().men;
        assert_eq!(
            after, 900.0,
            "empty pool must not resupply manpower for free"
        );
    }

    /// A partially-exhausted pool must only grant what it can cover (first-come-first-served).
    #[test]
    fn supply_limited_pool_grants_only_what_it_covers() {
        let (mut world, world_entity) = make_world(7); // pool covers only some of the gain
        let unit = spawn_unit(&mut world, 900.0); // gain = 10 (recruitment_rate), capped by pool
        let ctx = TickContext::build(&world, world_entity).unwrap();

        run(&mut world, world_entity, &ctx, 10.0);

        let after = world.get::<&UnitStats>(unit).unwrap().men;
        // gain (10) exceeds remaining pool (7) → resupply must be skipped entirely.
        assert_eq!(
            after, 900.0,
            "resupply must not exceed the available manpower pool"
        );
    }
}
